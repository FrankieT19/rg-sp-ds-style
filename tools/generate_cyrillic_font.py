# The Latin glyphs at the start of the bank are left untouched. New glyphs
# use the same 8x12 grid: uppercase starts at row 2, lowercase at row 4,
# and descenders use rows 10-11.
G = {}
def glyph(cp, top, rows):
    assert cp not in G, hex(cp)
    assert all(len(r) == 8 and set(r) <= {'.', '#'} for r in rows), hex(cp)
    assert top + len(rows) <= 12, hex(cp)
    assert all(r[0] == '.' and r[6] == '.' and r[7] == '.' for r in rows), 'ink outside columns 1..5: ' + hex(cp)
    G[cp] = (top, rows)

