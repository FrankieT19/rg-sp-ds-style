CYR_ORDER = [0x401] + list(range(0x410, 0x430)) + list(range(0x430, 0x450)) + [0x451]
assert len(CYR_ORDER) == 66 and all(cp in G for cp in CYR_ORDER), [hex(cp) for cp in CYR_ORDER if cp not in G]
assert len(G) == len(CYR_ORDER), [hex(cp) for cp in G if cp not in CYR_ORDER]


def glyph_bytes(cp):
    top, rows = G[cp]
    grid = ['........'] * 12
    for i, row in enumerate(rows):
        grid[top + i] = row
    return bytes(sum(1 << (7 - x) for x, c in enumerate(row) if c == '#') for row in grid)


text = layout.read_text(encoding='utf-8')
match = re.search(r'static const unsigned latin_codepoints\[\]=\{([^}]*)\};', text)
assert match, 'latin_codepoints[] not found'
base = [int(n) for n in match.group(1).split(',') if n.strip()]
latin = [cp for cp in base if not 0x400 <= cp <= 0x4FF]

data = asset.read_bytes()
base_bytes = len(latin) * 12
assert len(data) >= base_bytes, 'font bank is shorter than the Latin codepoint list'
new_data = data[:base_bytes] + b''.join(glyph_bytes(cp) for cp in CYR_ORDER)
asset.write_bytes(new_data)

new_list = latin + CYR_ORDER
text = text[:match.start(1)] + ','.join(str(cp) for cp in new_list) + text[match.end(1):]
layout.write_text(text, encoding='utf-8', newline='\n')
print(f'Latin glyphs: {len(latin)}, Cyrillic glyphs: {len(CYR_ORDER)}, font bytes: {len(new_data)}')
